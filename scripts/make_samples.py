"""
Builds a small, committed samples/ folder for trying the dashboard without
needing the full dataset: a few real NEU-DET defect images (known to trigger
FAIL), a few synthetic defect-free plates (known to trigger PASS - NEU-DET
itself has no "clean" images, every image in it has an annotated defect, so
a genuine negative example has to be synthesized), and a short demo video
mixing both.

Run after scripts/convert_neudet_to_yolo.py (needs data/yolo/test/images).
"""
import shutil
from pathlib import Path

import cv2
import numpy as np

PROJECT_ROOT = Path(__file__).resolve().parent.parent
TEST_IMAGES = PROJECT_ROOT / "data" / "yolo" / "test" / "images"
SAMPLES_DIR = PROJECT_ROOT / "samples"

# Real NEU-DET images, chosen because the trained model detects them with
# high confidence (see results.json per-class mAP) - reliable FAIL demos.
DEFECT_SAMPLES = {
    "defect_scratches.jpg": "scratches_1.jpg",
    "defect_patches.jpg": "patches_116.jpg",
    "defect_inclusion.jpg": "inclusion_1.jpg",
}

IMG_SIZE = 200
RNG_SEED = 7


def make_synthetic_clean_plate(seed: int) -> np.ndarray:
    """A plausible-looking brushed-metal grayscale plate with no defect."""
    rng = np.random.default_rng(seed)
    base = rng.normal(loc=150, scale=8, size=(IMG_SIZE, IMG_SIZE)).astype(np.float32)
    # Directional brushed-metal streaks: blur horizontally only.
    streaked = cv2.GaussianBlur(base, (1, 15), 0)
    streaked = cv2.GaussianBlur(streaked, (9, 1), 0)
    plate = np.clip(streaked, 0, 255).astype(np.uint8)
    return cv2.cvtColor(plate, cv2.COLOR_GRAY2BGR)


def main():
    if SAMPLES_DIR.exists():
        shutil.rmtree(SAMPLES_DIR)
    SAMPLES_DIR.mkdir(parents=True)

    for dest_name, src_name in DEFECT_SAMPLES.items():
        src = TEST_IMAGES / src_name
        if not src.exists():
            raise FileNotFoundError(f"{src} not found - run scripts/convert_neudet_to_yolo.py first.")
        shutil.copy2(src, SAMPLES_DIR / dest_name)
        print(f"Copied real defect sample: {dest_name} (from NEU-DET {src_name})")

    clean_names = []
    for i in range(2):
        img = make_synthetic_clean_plate(seed=RNG_SEED + i)
        name = f"clean_synthetic_{i + 1}.jpg"
        cv2.imwrite(str(SAMPLES_DIR / name), img)
        clean_names.append(name)
        print(f"Generated synthetic clean plate: {name}")

    # Short demo video: a few seconds alternating defect / clean frames,
    # each held for ~1s so a viewer can see each verdict clearly.
    video_path = SAMPLES_DIR / "demo_video.mp4"
    frame_sequence = list(DEFECT_SAMPLES.keys()) + clean_names
    fourcc = cv2.VideoWriter_fourcc(*"mp4v")
    writer = cv2.VideoWriter(str(video_path), fourcc, 1.0, (IMG_SIZE, IMG_SIZE))
    for name in frame_sequence:
        frame = cv2.imread(str(SAMPLES_DIR / name))
        for _ in range(2):  # ~2 seconds per frame at 1fps
            writer.write(frame)
    writer.release()
    print(f"Wrote demo video: {video_path}")

    readme = SAMPLES_DIR / "README.md"
    readme.write_text(
        "# Samples\n\n"
        "For trying the dashboard without the full dataset.\n\n"
        "## Real defects (from NEU-DET, should FAIL)\n"
        + "".join(f"- `{name}` (NEU-DET `{src}`)\n" for name, src in DEFECT_SAMPLES.items())
        + "\n## Synthetic clean plates (should PASS)\n"
        "NEU-DET has no defect-free images - every image in the dataset has an "
        "annotated defect. These are synthetic brushed-metal textures generated by "
        "scripts/make_samples.py specifically to have no defect, so the PASS path "
        "has something real to demonstrate against.\n"
        + "".join(f"- `{name}`\n" for name in clean_names)
        + "\n## Video\n"
        "- `demo_video.mp4` - alternates through the samples above, ~2s per frame.\n",
        encoding="utf-8",
    )
    print(f"Wrote {readme}")


if __name__ == "__main__":
    main()
